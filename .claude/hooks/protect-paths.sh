#!/usr/bin/env bash
# PreToolUse (Edit|Write): block edits to licensed raw data, secrets and generated warehouses.
# Exit 2 = block; stderr goes back to Claude so it can change course.
set -euo pipefail

FILE_PATH=$(python3 -c 'import json,sys; print(json.load(sys.stdin).get("tool_input",{}).get("file_path",""))')
FILE_PATH="${FILE_PATH//\\//}"

case "$FILE_PATH" in
  */data/raw/*|data/raw/*)
    echo "Blocked: $FILE_PATH is licensed source data (NSW PSI is CC BY-NC-ND). Change the parser or staging SQL instead." >&2
    exit 2 ;;
  *.env|*/.env.*|.env.*)
    echo "Blocked: $FILE_PATH holds secrets. Ask the user to edit it." >&2
    exit 2 ;;
  *.duckdb|*.duckdb.wal)
    echo "Blocked: $FILE_PATH is generated. Change models/ and run make build." >&2
    exit 2 ;;
  */data/sample/*|data/sample/*)
    echo "Blocked: sample files are generated by src/oda/samples.py. Edit the generator and run make sample." >&2
    exit 2 ;;
esac
exit 0
